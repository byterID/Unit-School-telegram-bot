async def seed(db: Database, force: bool = False) -> None:
    """Наполняет базу демонстрационными данными."""
    if not force and not await db.is_empty():
        logger.info("База уже содержит данные — пропускаю наполнение")
        return

    # 1. Группы
    for name, sort in GROUPS:
        await db.add_group(name, sort)
    group_ids = {row["name"]: row["id"] for row in await db.get_groups()}

    # 2. Преподаватели
    existing = {row["full_name"] for row in await db.get_teachers()}
    for full_name, subject, phone, room, email in TEACHERS:
        if full_name not in existing:
            await db.add_teacher(full_name, subject, phone, room, email)
    teacher_ids = {row["full_name"]: row["id"] for row in await db.get_teachers()}

    # 3. Расписание
    for group_name, days in SCHEDULE.items():
        group_id = group_ids.get(group_name)
        if group_id is None:
            continue
        for weekday, lessons in days.items():
            for number, (subject, room, teacher_name) in enumerate(lessons, start=1):
                start, end = BELLS.get(number, ("00:00", "00:00"))
                await db.add_lesson(
                    group_id=group_id,
                    weekday=weekday,
                    number=number,
                    time_start=start,
                    time_end=end,
                    subject=subject,
                    room=room,
                    teacher_id=teacher_ids.get(teacher_name or ""),
                )

    # 4. Меню
    for weekday, meals in MENU.items():
        for meal_type, dishes in meals.items():
            await db.clear_meal(weekday, meal_type)
            for name in dishes:
                await db.add_dish(weekday, meal_type, name)

    # 5. FAQ
    if not await db.get_faq():
        await db.executemany(
            "INSERT INTO faq (question, answer, sort) VALUES (?, ?, ?)",
            [(q, a, i) for i, (q, a) in enumerate(FAQ, start=1)],
        )

    logger.info("Демонстрационные данные загружены")


if __name__ == "__main__":
    # Позволяет перезалить данные вручную: python -m data.sample_data --force
    import asyncio
    import sys

    import config
    from database import init_db

    async def main() -> None:
        logging.basicConfig(level=logging.INFO)
        database = init_db(config.DB_PATH)
        await database.connect()
        try:
            await seed(database, force="--force" in sys.argv)
        finally:
            await database.close()

    asyncio.run(main())
